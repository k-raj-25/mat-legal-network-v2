<h2>1. What are cookies?</h2>
<p>Cookies are small text files stored by your browser. They help a website remember information between pages and visits.</p>

<h2>2. Cookies we use</h2>
<p>We use only <strong>strictly necessary</strong> cookies required for the website to work securely. We do <strong>not</strong> use advertising or cross-site tracking cookies.</p>
<ul>
    <li><strong>Session cookie</strong> – keeps you logged in (for lawyers and staff) and remembers form input between pages. Expires when you close the browser or after a period of inactivity.</li>
    <li><strong>XSRF-TOKEN</strong> – protects forms against cross-site request forgery attacks.</li>
    <li><strong>remember_web_*</strong> – set only if you choose “Keep me logged in”.</li>
    <li><strong>mln_disclaimer</strong> – remembers that you accepted our Disclaimer, so we don’t show it on every page (180 days).</li>
</ul>

